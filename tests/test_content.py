def journey_with_contexts(**changes) -> tuple:
    """A two-stage tile map and matching contexts, with ``changes`` applied to the contexts' lhc entry."""
    tiles = {"lhc": [{"id": "sorting", "label": "Sorting", "benefiting": [], "negativelyImpacted": []},
                     {"id": "drying", "label": "Drying", "benefiting": [], "negativelyImpacted": []}],
             "hair": [{"id": "inspire", "label": "Inspire", "benefiting": [], "negativelyImpacted": []}]}
    context = {"henkelBrands": "Persil", "competitors": "Tide", "opportunity": "A garment advisor."}
    contexts = {"lhc": {"sorting": dict(context), "drying": dict(context)}, "hair": {"inspire": dict(context)}}
    for key, value in changes.items():
        if value is ...:
            del contexts["lhc"][key]
        else:
            contexts["lhc"][key] = value
    return contexts, tiles


class TestContextsProblem:
    def test_the_contexts_of_the_base_content_fit_its_tiles(self):
        assert contexts_problem(*journey_with_contexts()) is None

    @pytest.mark.parametrize("contexts, reason", [
        ([], "exactly the journeys lhc and hair"),
        ({"lhc": {}}, "exactly the journeys lhc and hair"),
        ({"lhc": {}, "hair": {}, "body": {}}, "exactly the journeys lhc and hair"),
        ({"lhc": [], "hair": {}}, "contexts.lhc must map stage ids to contexts"),
        (journey_with_contexts(loading={"henkelBrands": "", "competitors": "", "opportunity": ""})[0],
         "contexts.lhc names loading, which are not stages of the journey"),
        (journey_with_contexts(drying=...)[0], "contexts.lhc lacks the stages drying"),
        (journey_with_contexts(sorting={"henkelBrands": "Persil", "competitors": "Tide"})[0],
         "contexts.lhc.sorting must hold henkelBrands, competitors, opportunity as text, and nothing else"),
        (journey_with_contexts(sorting={"henkelBrands": "Persil", "competitors": "Tide", "opportunity": None})[0],
         "contexts.lhc.sorting must hold"),
        (journey_with_contexts(sorting={"henkelBrands": "Persil", "competitors": "Tide", "opportunity": "x",
                                        "threat": "y"})[0], "contexts.lhc.sorting must hold"),
        (journey_with_contexts(sorting="Persil")[0], "contexts.lhc.sorting must hold"),
    ])
    def test_contexts_that_do_not_fit_the_tiles_are_refused(self, contexts, reason):
        tiles = journey_with_contexts()[1]
        assert reason in contexts_problem(contexts, tiles)

    def test_a_context_for_a_stage_of_the_other_journey_is_refused(self):
        contexts, tiles = journey_with_contexts()
        contexts["hair"]["sorting"] = contexts["hair"]["inspire"]
        assert contexts_problem(contexts, tiles) == "contexts.hair names sorting, which are not stages of the journey"


def view(**changes) -> dict:
    """One well-formed view of two rows, with ``changes`` applied to the view (a key set to ... is left out)."""
    source = {"label": "Henkel FY2025: group gross margin 50.8%", "url": "https://www.henkel.com/ar2025",
              "grade": "reported"}
    size = {"label": "Euromonitor via Happi: Europe hair care $23.2bn (2025)", "url": "https://www.happi.com/x",
            "detail": "DERIVATION: a share of the world total.", "grade": "estimate", "denomination": "RSP"}
    row = {"label": "Brand owner", "sublabel": "Net sales", "revenueShare": 0.6, "gp1Margin": 0.5,
           "revenueCAGR": 0.03, "gp1DeltaBps": 50, "revenueDriver": "Volume.", "marginDriver": "Mix.",
           "note": "Henkel, P&G", "sources": {"revenue": [size], "margin": [source]}}
    base = {"id": "hair_value_chain", "title": "Hair Care: value chain", "subtitle": "GP1 proxy", "poolSize": "~€153bn",
            "poolSizeEurBn": 152.6, "group": "Hair", "kind": "ValueChain", "construction": "Each tier on its own base.",
            "insights": ["Retail holds the margin."],
            "items": [{**row, "id": "h_vc_1"}, {**row, "id": "h_vc_2", "revenueShare": 0.4}]}
    out = {**base, **changes}
    return {k: v for k, v in out.items() if v is not ...}


def views_with(*views_given) -> list:
    """Every view of the dashboard, each the well-formed view under its own id, the given ones replacing theirs."""
    def known(v) -> bool:
        return isinstance(v, dict) and v.get("id") in explorer.VIEW_IDS
    given = {v["id"]: v for v in views_given if known(v)}
    return [given.get(view_id, view(id=view_id)) for view_id in explorer.VIEW_IDS] \
        + [v for v in views_given if not known(v)]


def row(**changes) -> dict:
    """The first row of the well-formed view with ``changes`` applied (a key set to ... is left out)."""
    item = {**view()["items"][0], **changes}
    return {k: v for k, v in item.items() if v is not ...}


def with_rows(*rows) -> dict:
    return view(items=list(rows))


def with_source(side: str, **changes) -> dict:
    """The well-formed view whose first row's first source on ``side`` has ``changes`` applied."""
    first = view()["items"][0]
    sources = copy.deepcopy(first["sources"])
    sources[side][0] = {k: v for k, v in {**sources[side][0], **changes}.items() if v is not ...}
    return with_rows({**first, "sources": sources}, {**view()["items"][1]})


