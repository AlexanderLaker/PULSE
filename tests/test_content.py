# ── the generator refuses broken content ────────────────────────────────────

class TestGeneratorRefusals:
    @pytest.fixture
    def inputs(self, monkeypatch, tmp_path):
        """The generator pointed at copies of the content files and at outputs in a temporary folder."""
        gen = _generator()
        paths = {"journey": tmp_path / "consumer_journey.json", "pools": tmp_path / "profit_pools.json"}
        paths["journey"].write_text(dumps(JOURNEY), encoding="utf-8")
        paths["pools"].write_text(dumps(POOLS), encoding="utf-8")
        monkeypatch.setattr(gen, "JOURNEY_IN", paths["journey"])
        monkeypatch.setattr(gen, "POOLS_IN", paths["pools"])
        monkeypatch.setattr(gen, "JOURNEY_OUT", tmp_path / "journey_content.py")
        monkeypatch.setattr(gen, "EXPLORER_OUT", tmp_path / "explorer_content.py")
        return gen, paths, tmp_path

    @staticmethod
    def _refuses(gen, folder, capsys, fragment: str) -> None:
        assert gen.main([]) == 1
        captured = capsys.readouterr()
        assert captured.err.startswith("REFUSING: ") and fragment in captured.err
        assert not (folder / "journey_content.py").exists() and not (folder / "explorer_content.py").exists()
        assert gen.main(["--check"]) == 1   # the check refuses the same way, without naming a stale file
        assert "STALE" not in capsys.readouterr().out

    def test_the_copies_build(self, inputs):
        gen, _, folder = inputs
        assert gen.main([]) == 0
        assert (folder / "journey_content.py").read_text(encoding="utf-8") == \
            (REPO / "prism" / "journey_content.py").read_text(encoding="utf-8")

    def test_a_tile_map_the_api_would_not_store_is_refused(self, inputs, capsys):
        gen, paths, folder = inputs
        broken = copy.deepcopy(JOURNEY)
        broken["tiles"]["lhc"][0]["benefiting"][0]["driverCodes"] = ["C-99"]
        paths["journey"].write_text(dumps(broken), encoding="utf-8")
        self._refuses(gen, folder, capsys, "consumer_journey.json: tiles: tile "
                                            "'lhc.sorting.exp.ai-stain-fabric-recognition-apps' cites C-99")

    def test_contexts_that_do_not_fit_the_tiles_are_refused(self, inputs, capsys):
        gen, paths, folder = inputs
        broken = copy.deepcopy(JOURNEY)
        broken["contexts"]["hair"]["grooming"] = broken["contexts"]["hair"]["inspire"]
        paths["journey"].write_text(dumps(broken), encoding="utf-8")
        self._refuses(gen, folder, capsys, "consumer_journey.json: contexts.hair names grooming")

    def test_a_view_the_dashboard_could_not_render_is_refused(self, inputs, capsys):
        gen, paths, folder = inputs
        broken = copy.deepcopy(POOLS)
        broken["views"][2]["items"][0]["gp1Margin"] = 1.2
        paths["pools"].write_text(dumps(broken), encoding="utf-8")
        self._refuses(gen, folder, capsys, "profit_pools.json: view 'hair_categories': row")

    @pytest.mark.parametrize("name, text, fragment", [
        ("journey", '{"tiles": {}}', "consumer_journey.json must hold exactly tiles, contexts"),
        ("pools", '{"views": [], "notes": []}', "profit_pools.json must hold exactly views"),
        ("pools", "{not json", "profit_pools.json: "),
    ])
    def test_a_file_of_the_wrong_shape_is_refused(self, inputs, capsys, name, text, fragment):
        gen, paths, folder = inputs
        paths[name].write_text(text, encoding="utf-8")
        self._refuses(gen, folder, capsys, fragment)

    def test_a_missing_file_is_refused(self, inputs, capsys):
        gen, paths, folder = inputs
        paths["pools"].unlink()
        self._refuses(gen, folder, capsys, "profit_pools.json: ")
