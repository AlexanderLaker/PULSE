class TestContentFiles:
    def test_the_journey_file_holds_the_tiles_and_the_contexts(self):
        assert set(JOURNEY) == {"tiles", "contexts"}
        assert content_problem(JOURNEY["tiles"]) is None
        assert contexts_problem(JOURNEY["contexts"], JOURNEY["tiles"]) is None
        assert bundled_journey() == JOURNEY["tiles"]
        tiles = [t for j in journey.JOURNEYS for s in JOURNEY["tiles"][j] for side in journey.SIDES for t in s[side]]
        assert len(tiles) == 300 and len({t["id"] for t in tiles}) == 300
        assert [len(JOURNEY["tiles"][j]) for j in journey.JOURNEYS] == [13, 8]
        for j in journey.JOURNEYS:
            assert list(JOURNEY["contexts"][j]) == [s["id"] for s in JOURNEY["tiles"][j]]

    def test_the_pools_file_holds_the_views(self):
        assert set(POOLS) == {"views"}
        assert views_problem(POOLS["views"]) is None
        assert [v["id"] for v in POOLS["views"]] == list(explorer.VIEW_IDS)
        assert {v["group"] for v in POOLS["views"]} == set(explorer.GROUPS)
        assert {v["kind"] for v in POOLS["views"]} == set(explorer.KINDS)
        sources = [s for v in POOLS["views"] for i in v["items"] for side in explorer.SOURCE_SIDES
                   for s in i["sources"][side]]
        assert sources and all(s["url"].startswith("https://") for s in sources)
        assert {s["grade"] for s in sources} == set(explorer.GRADES)

    def test_neither_file_carries_an_em_dash_or_an_escaped_paragraph_break(self):
        for path in (JOURNEY_CONTENT, POOLS_CONTENT):
            text = path.read_text(encoding="utf-8")
            assert chr(0x2014) not in text, path.name
            assert "\\\\n" not in text, path.name


