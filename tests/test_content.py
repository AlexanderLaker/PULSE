"""The content behind the API: data/content/*.json, their validators and the generated modules.

The Consumer Journey's base tile map and stage contexts and the Profit Pool
Explorer's views are hand-authored JSON (data/content/) that
scripts/build_content.py validates and writes as Python literals to
prism/journey_content.py and prism/explorer_content.py, which the API serves
to a signed-in user with a role. The modules must equal the JSON exactly, the
generator's --check must pass on the committed modules, and the validators
must refuse what the dashboard could not render.
"""
import ast
import copy
import json
from pathlib import Path

import pytest

from prism import explorer, journey
from prism.explorer import views_problem
from prism.journey import content_problem, contexts_problem
from support import JOURNEY_CONTENT, POOLS_CONTENT, bundled_journey, load_module

REPO = Path(__file__).resolve().parents[1]
JOURNEY = json.loads(JOURNEY_CONTENT.read_text(encoding="utf-8"))
POOLS = json.loads(POOLS_CONTENT.read_text(encoding="utf-8"))


def _generator():
    return load_module("scripts/build_content.py", "build_content")


def dumps(value) -> str:
    """One text for a JSON value: equal texts mean equal values, types and key order."""
    return json.dumps(value, ensure_ascii=False)


