class TestGeneratedModules:
    def test_the_modules_equal_the_json(self):
        """Value for value and text for text: the same strings, numbers (an integer stays an integer), booleans,
        nulls and key order; nothing added, nothing lost."""
        from prism.explorer_content import VIEWS
        from prism.journey_content import CONTEXTS, TILES
        assert TILES == JOURNEY["tiles"] and CONTEXTS == JOURNEY["contexts"] and VIEWS == POOLS["views"]
        assert dumps(TILES) == dumps(JOURNEY["tiles"])
        assert dumps(CONTEXTS) == dumps(JOURNEY["contexts"])
        assert dumps(VIEWS) == dumps(POOLS["views"])

    def test_the_modules_are_literals_with_the_generated_header(self):
        """Plain literals (no code, no imports) that the API loads without the engine, each saying what
        generated it and that it is not edited by hand."""
        for name, names in (("journey_content", {"TILES", "CONTEXTS"}), ("explorer_content", {"VIEWS"})):
            source = (REPO / "prism" / f"{name}.py").read_text(encoding="utf-8")
            tree = ast.parse(source)
            assert isinstance(tree.body[0], ast.Expr) and isinstance(tree.body[0].value, ast.Constant)
            header = " ".join(tree.body[0].value.value.split())
            assert "Generated by scripts/build_content.py from data/content/" in header
            assert "Do not edit this file: change the JSON and re-run the generator." in header
            assignments = [node for node in tree.body[1:]]
            assert all(isinstance(node, ast.Assign) for node in assignments)
            assert {node.targets[0].id for node in assignments} == names
            for node in assignments:
                ast.literal_eval(node.value)   # a literal, nothing else

    def test_the_check_passes_on_the_committed_modules(self, capsys):
        assert _generator().main(["--check"]) == 0
        assert "OK: the committed modules match the content files" in capsys.readouterr().out

    def test_the_generator_reproduces_the_committed_modules(self, monkeypatch, tmp_path, capsys):
        gen = _generator()
        monkeypatch.setattr(gen, "JOURNEY_OUT", tmp_path / "journey_content.py")
        monkeypatch.setattr(gen, "EXPLORER_OUT", tmp_path / "explorer_content.py")
        assert gen.main([]) == 0
        out = capsys.readouterr().out
        assert "wrote" in out and "journey_content.py" in out and "explorer_content.py" in out
        for name in ("journey_content.py", "explorer_content.py"):
            assert (tmp_path / name).read_text(encoding="utf-8") == (REPO / "prism" / name).read_text(encoding="utf-8")

    def test_the_check_fails_on_a_stale_or_missing_module(self, monkeypatch, tmp_path, capsys):
        gen = _generator()
        stale = tmp_path / "journey_content.py"
        stale.write_text((REPO / "prism" / "journey_content.py").read_text(encoding="utf-8").replace(
            '"label": "Sorting"', '"label": "Sorting the wash"'), encoding="utf-8")
        monkeypatch.setattr(gen, "JOURNEY_OUT", stale)
        monkeypatch.setattr(gen, "EXPLORER_OUT", tmp_path / "missing.py")
        assert gen.main(["--check"]) == 1
        out = capsys.readouterr().out
        assert "STALE: " in out and "Re-run scripts/build_content.py" in out
        assert stale.read_text(encoding="utf-8") != (REPO / "prism" / "journey_content.py").read_text(encoding="utf-8")
        assert not (tmp_path / "missing.py").exists()   # --check writes nothing


class TestLiteral:
    @pytest.mark.parametrize("value", [
        None, True, False, 0, -50, 152.6, 1.0, 1e-07, "", "plain", 'quotes " and \' and \\ backslash',
        "line\nbreak and tab\t and unicode: Schwarzkopf’s €82bn, 2-in-1 …", "a } brace { and a ] bracket [",
        [], {}, [[], {}, [None]], {"a": {"b": [1, 2.5, "3", True, None]}, "": {}},
    ])
    def test_a_json_value_round_trips(self, value):
        """The literal reads back as the value, with its types: 1.0 stays a float, True never becomes 1."""
        text = _generator().literal(value)
        back = ast.literal_eval(text)
        assert back == value and dumps(back) == dumps(value)
        assert type(back) is type(value)

    def test_strings_are_double_quoted_json_escaped_literals(self):
        gen = _generator()
        assert gen.literal('say "hi"\n') == '"say \\"hi\\"\\n"'
        assert gen.literal("ü") == '"ü"'   # not an escape: the module stays readable
        assert gen.q(None) == '""'

    def test_the_layout_nests_by_four_spaces_with_the_file_order(self):
        text = _generator().literal({"b": [1, {"d": None, "c": True}], "a": "x"})
        assert text == ('{\n    "b": [\n        1,\n        {\n            "d": None,\n            "c": True,\n'
                        '        },\n    ],\n    "a": "x",\n}')

    def test_what_is_not_json_is_refused(self):
        with pytest.raises(TypeError):
            _generator().literal({"a": {1, 2}})


