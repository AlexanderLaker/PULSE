"""Generate the seed module and the display-code map from the driver base.

Input
  data/drivers/driver_base.json      the drivers: scores, exposures, sources

Outputs (committed, never edited by hand)
  prism/seed_drivers.py              the drivers a new database is seeded with, in id order
  data/driverCodeMap.ts              display code <-> driver id and force for the dashboard,
                                     and nothing else of the driver
  prism/driver_names.py              each driver's short name, long name, descriptor and
                                     boundary sentence by driver id, which the API serves with
                                     the stored drivers (no database holds them)

The base is validated before anything is written (prism/driver_base.py): every
model input by the engine's rules (prism.drivers.simulation_problems), an
onset and a peak inside the horizon, and sources the editor can save again,
at least one of tier S, A or B behind every driver.

    python3 scripts/generate_seed.py            write the three files
    python3 scripts/generate_seed.py --check    exit 1 if a committed file differs
"""
from __future__ import annotations

import argparse
import collections
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from prism.config import CATEGORIES, FORCES, REGIONS  # noqa: E402
from prism.driver_base import InvalidBaseError, load_base  # noqa: E402

SEED_OUT = ROOT / "prism" / "seed_drivers.py"
CODEMAP_OUT = ROOT / "data" / "driverCodeMap.ts"
NAMES_OUT = ROOT / "prism" / "driver_names.py"


def q(s) -> str:
    """A double-quoted Python string literal (JSON escapes are valid Python)."""
    return json.dumps("" if s is None else str(s), ensure_ascii=False)


def render_seed(drivers: list) -> str:
    by_force = collections.Counter(d["force"] for d in drivers)
    by_dir = collections.Counter(d["direction"] for d in drivers)
    lines = []
    a = lines.append
    a('"""The Profit Pool Drivers a new database is seeded with.')
    a("")
    a("Generated by scripts/generate_seed.py from data/drivers/driver_base.json. Do")
    a("not edit this file: change the JSON and re-run the generator.")
    a("")
    a(f"{len(drivers)} drivers: " + ", ".join(f"{f} {by_force.get(f, 0)}" for f in FORCES) + ";")
    a(f"{by_dir.get('Contraction', 0)} Contraction, {by_dir.get('Expansion', 0)} Expansion.")
    a('"""')
    a("import copy")
    a("")
    a("from prism.config import CATEGORIES, REGIONS")
    a("from prism.drivers import Driver")
    a("")
    a("")
    a("def _categories(*scores):")
    a("    return dict(zip(CATEGORIES, scores))")
    a("")
    a("")
    a("def _regions(*scores):")
    a("    return dict(zip(REGIONS, scores))")
    a("")
    a("")
    a("DRIVERS = [")
    force = None
    for d in drivers:
        if d["force"] != force:
            force = d["force"]
            a(f"    # ── {force} ({by_force[force]}) " + "─" * max(0, 60 - len(force)))
        a(f"    # {d['code']} · {d['theme']} · {d['foresight_tier']}, {d['scope']} · "
          f"megatrend: {d['megatrend']} · first observed {d['first_observed']}")
        cat, reg = d["category_exposure"], d["regional_exposure"]
        a("    Driver(")
        a(f"        id={q(d['id'])}, force={q(d['force'])},")
        a(f"        name={q(d['name'])},")
        a(f"        description={q(d['description'])},")
        a(f"        direction={q(d['direction'])}, probability={d['probability']}, start_year={d['start_year']},")
        a(f"        gp1_pct_affected={float(d['gp1_pct_affected'])!r}, peak_year={d['peak_year']}, "
          f"diffusion_curve={q(d['diffusion_curve'])}, uncertainty={d['uncertainty']},")
        a(f"        confidence={q(d['confidence'])},")
        a("        category_exposure=_categories(" + ", ".join(str(cat[c]) for c in CATEGORIES) + "),")
        a("        regional_exposure=_regions(" + ", ".join(str(reg[r]) for r in REGIONS) + "),")
        a(f"        vc_epicentre={q(d['vc_epicentre'])},")
        a("        sources=[")
        for s in d["sources"]:
            a(f"            {{\"title\": {q(s['title'])}, \"url\": {q(s['url'])}, "
              f"\"tier\": {q(s['tier'])}, \"published\": {q(s['published'])}}},")
        a("        ],")
        a("    ),")
    a("]")
    a("")
    a("")
    a("def get_seed_drivers() -> list:")
    a('    """Fresh copies of the seed drivers, each with its baseline recorded."""')
    a("    drivers = copy.deepcopy(DRIVERS)")
    a("    for d in drivers:")
    a("        d.baseline = d.scores()")
    a("    return drivers")
    return "\n".join(lines) + "\n"


def render_codemap(drivers: list) -> str:
    lines = []
    a = lines.append
    a("/**")
    a(" * Display codes of the drivers (C-01, K-13, ...): the driver each one names")
    a(" * and its force.")
    a(" *")
    a(" * Generated by scripts/generate_seed.py from data/drivers/driver_base.json;")
    a(" * do not edit. A code is the force letter (C Consumer, K Customer, T")
    a(" * Technology, G Government, E Environmental, X Competitive) and the number")
    a(" * of the driver id: 'C-01' is consumer_r01. The Consumer Journey content")
    a(" * cites drivers by these codes. The map carries no name, direction or")
    a(" * text: those come from the drivers the dashboard loads from the API,")
    a(" * which answers a signed-in user with a role and nobody else.")
    a(" */")
    a("")
    a("import type { ForceName } from '@/types';")
    a("")
    a("export const DRIVER_CODE_MAP: Record<string, { driverId: string; force: ForceName }> = {")
    for d in sorted(drivers, key=lambda x: x["code"]):
        info = {"driverId": d["id"], "force": d["force"]}
        a(f"  '{d['code']}': {json.dumps(info, ensure_ascii=False)},")
    a("};")
    a("")
    a("const ID_TO_CODE: Record<string, string> = Object.fromEntries(")
    a("  Object.entries(DRIVER_CODE_MAP).map(([code, v]) => [v.driverId, code]),")
    a(");")
    a("")
    a("export const codeForDriverId = (driverId: string): string | undefined => ID_TO_CODE[driverId];")
    return "\n".join(lines) + "\n"


def render_names(drivers: list) -> str:
    lines = []
    a = lines.append
    a('"""The names of every driver, by driver id.')
    a("")
    a("Generated by scripts/generate_seed.py from data/drivers/driver_base.json. Do")
    a("not edit this file: change the JSON and re-run the generator. The API serves")
    a("each driver's names with the stored driver, and no database holds them; a")
    a("driver the base does not know has none (docs/DRIVERS.md, Names).")
    a('"""')
    a("")
    a("NAMES = {")
    for d in drivers:
        a(f"    {q(d['id'])}: {{")
        a(f"        \"short_name\": {q(d['short_name'])},")
        a(f"        \"long_name\": {q(d['long_name'])},")
        a(f"        \"descriptor\": {q(d['descriptor'])},")
        a(f"        \"boundary\": {q(d.get('boundary', ''))},")
        a("    },")
    a("}")
    return "\n".join(lines) + "\n"


def generate() -> tuple:
    try:
        drivers = load_base()
    except InvalidBaseError as e:
        raise SystemExit(str(e)) from None
    # In id order, the order the database returns them in, so the seed and a
    # seeded database hand the engine the drivers in the same order (the
    # copula pairs draws with drivers by position).
    drivers = sorted(drivers, key=lambda d: d["id"])
    return {SEED_OUT: render_seed(drivers), CODEMAP_OUT: render_codemap(drivers),
            NAMES_OUT: render_names(drivers)}, drivers


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="compare with the committed files; write nothing")
    args = ap.parse_args(argv)
    outputs, drivers = generate()
    if args.check:
        stale = [p for p, src in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != src]
        for p in stale:
            print(f"STALE: {p.relative_to(ROOT)} differs from the generator output")
        print("Re-run scripts/generate_seed.py" if stale else "OK: the committed files match the generator")
        return 1 if stale else 0
    for path, src in outputs.items():
        path.write_text(src, encoding="utf-8")
    counts = collections.Counter(d["force"] for d in drivers)
    print(f"wrote {', '.join(str(p.relative_to(ROOT)) for p in outputs)}: {len(drivers)} drivers ("
          + ", ".join(f"{f} {counts[f]}" for f in FORCES) + ")")
    return 0


if __name__ == "__main__":
    sys.exit(main())
