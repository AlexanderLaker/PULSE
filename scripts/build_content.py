"""Generate the content modules the API serves from the hand-authored JSON.

Inputs
  data/content/consumer_journey.json   the Consumer Journey: the base tile map ("tiles",
                                       {lhc, hair}) and the stage contexts ("contexts")
  data/content/profit_pools.json       the Profit Pool Explorer's views ("views")

Outputs (committed, never edited by hand)
  prism/journey_content.py             TILES and CONTEXTS, served by GET /api/v1/journey
  prism/explorer_content.py            VIEWS, served by GET /api/v1/explorer

The content is confidential, so it lives here and behind the API, never in
the dashboard's code (app/, components/, hooks/ and lib/ import neither the
JSON nor these modules; tests/test_repository.py checks). Both files are
validated before anything is written: the tile map by the rule every stored
version passes (prism.journey.content_problem), the contexts against the
stages of that map (prism.journey.contexts_problem) and the views by the
Explorer's rules (prism.explorer.views_problem). The modules hold the JSON as
Python literals: strings as double-quoted literals with JSON escapes, true,
false and null as True, False and None, numbers and key order as in the file.

    python3 scripts/build_content.py            write both modules
    python3 scripts/build_content.py --check    exit 1 if a committed module differs
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from prism.explorer import views_problem  # noqa: E402
from prism.journey import JOURNEYS, SIDES, content_problem, contexts_problem  # noqa: E402

JOURNEY_IN = ROOT / "data" / "content" / "consumer_journey.json"
POOLS_IN = ROOT / "data" / "content" / "profit_pools.json"
JOURNEY_OUT = ROOT / "prism" / "journey_content.py"
EXPLORER_OUT = ROOT / "prism" / "explorer_content.py"
INDENT = "    "


class InvalidContentError(ValueError):
    """A content file does not hold what the dashboard renders; nothing is written."""


def shown(path: Path) -> str:
    """A path as the messages name it: relative to the repository when inside it."""
    return str(path.relative_to(ROOT)) if path.is_relative_to(ROOT) else str(path)


def q(s) -> str:
    """A double-quoted Python string literal (JSON escapes are valid Python)."""
    return json.dumps("" if s is None else str(s), ensure_ascii=False)


def literal(value, depth: int = 0) -> str:
    """A Python literal for a JSON value, one key or element per line, nested
    by four spaces. Reading the module back gives the JSON value exactly:
    strings, integers, floats, True, False and None in the file's key order."""
    if value is None:
        return "None"
    if value is True:
        return "True"
    if value is False:
        return "False"
    if isinstance(value, str):
        return q(value)
    if isinstance(value, (int, float)):
        return repr(value)
    pad, inner = INDENT * depth, INDENT * (depth + 1)
    if isinstance(value, list):
        if not value:
            return "[]"
        return "[\n" + "".join(f"{inner}{literal(v, depth + 1)},\n" for v in value) + f"{pad}]"
    if isinstance(value, dict):
        if not value:
            return "{}"
        return ("{\n" + "".join(f"{inner}{q(k)}: {literal(v, depth + 1)},\n" for k, v in value.items())
                + f"{pad}}}")
    raise TypeError(f"{type(value).__name__} is not a JSON value")


def load(path: Path, keys: tuple) -> dict:
    """The JSON object at ``path``, which must hold exactly ``keys``."""
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as e:
        raise InvalidContentError(f"{shown(path)}: {e}") from None
    if not isinstance(data, dict) or set(data) != set(keys):
        raise InvalidContentError(f"{shown(path)} must hold exactly {', '.join(keys)}")
    return data


def render_journey(tiles: dict, contexts: dict) -> str:
    stages = sum(len(tiles[j]) for j in JOURNEYS)
    n_tiles = sum(len(stage[side]) for j in JOURNEYS for stage in tiles[j] for side in SIDES)
    lines = [
        '"""The Consumer Journey\'s base content: the tile map the API serves until an',
        "admin saves an edit (TILES, the journeys lhc and hair) and the stage contexts it",
        "serves with every version (CONTEXTS: per journey, by stage id, the HCB brands in",
        "play, the competitors' moves and the opportunity).",
        "",
        "Generated by scripts/build_content.py from data/content/consumer_journey.json.",
        "Do not edit this file: change the JSON and re-run the generator. The content",
        "is confidential: GET /api/v1/journey serves it to a signed-in user with a role,",
        "and the dashboard's code carries none of it.",
        "",
        f"{n_tiles} tiles in {stages} stages (" + ", ".join(f"{j} {len(tiles[j])}" for j in JOURNEYS) + ").",
        '"""',
        "",
        f"TILES = {literal(tiles)}",
        "",
        f"CONTEXTS = {literal(contexts)}",
    ]
    return "\n".join(lines) + "\n"


def render_explorer(views: list) -> str:
    rows = sum(len(v["items"]) for v in views)
    lines = [
        '"""The Profit Pool Explorer\'s views (VIEWS): where the profit sits in the Hair',
        "and the Laundry & Home Care industries and how each pool develops, every figure",
        "sourced and graded (docs/EXPLORER.md). The arithmetic is lib/profitPoolData.ts.",
        "",
        "Generated by scripts/build_content.py from data/content/profit_pools.json. Do",
        "not edit this file: change the JSON and re-run the generator. The content is",
        "confidential: GET /api/v1/explorer serves it to a signed-in user with a role,",
        "and the dashboard's code carries none of it.",
        "",
        f"{len(views)} views, {rows} rows:",
        *(f"  {v['id']} {len(v['items'])}" for v in views),
        '"""',
        "",
        f"VIEWS = {literal(views)}",
    ]
    return "\n".join(lines) + "\n"


def generate() -> dict:
    """The two modules by output path, from validated content; InvalidContentError otherwise."""
    journey = load(JOURNEY_IN, ("tiles", "contexts"))
    problem = content_problem(journey["tiles"])
    if problem:
        raise InvalidContentError(f"{shown(JOURNEY_IN)}: tiles: {problem}")
    problem = contexts_problem(journey["contexts"], journey["tiles"])
    if problem:
        raise InvalidContentError(f"{shown(JOURNEY_IN)}: {problem}")
    pools = load(POOLS_IN, ("views",))
    problem = views_problem(pools["views"])
    if problem:
        raise InvalidContentError(f"{shown(POOLS_IN)}: {problem}")
    return {JOURNEY_OUT: render_journey(journey["tiles"], journey["contexts"]),
            EXPLORER_OUT: render_explorer(pools["views"])}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="compare with the committed modules; write nothing")
    args = ap.parse_args(argv)
    try:
        outputs = generate()
    except InvalidContentError as e:
        print(f"REFUSING: {e}", file=sys.stderr)
        return 1
    if args.check:
        stale = [p for p, src in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != src]
        for p in stale:
            print(f"STALE: {shown(p)} differs from the generator output")
        print("Re-run scripts/build_content.py" if stale else "OK: the committed modules match the content files")
        return 1 if stale else 0
    for path, src in outputs.items():
        path.write_text(src, encoding="utf-8")
        print(f"wrote {shown(path)} ({len(src.encode('utf-8')):,} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
